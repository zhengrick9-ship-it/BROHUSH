function knockoutRange(
  start: number,
  end: number,
  stage: string,
  label: string,
  dates: string[],
) {
  const count = end - start + 1
  return Array.from({ length: count }, (_, index) => {
    const dateIndex = Math.min(
      dates.length - 1,
      Math.floor((index * dates.length) / count),
    )
    const matchNumber = start + index
    return {
      sourceMatchNumber: matchNumber,
      matchDate: dates[dateIndex],
      kickoffAt: null,
      groupName: null,
      stage,
      roundNumber: null,
      homeTeam: `${label}席位 ${index * 2 + 1}`,
      awayTeam: `${label}席位 ${index * 2 + 2}`,
    }
  })
}
